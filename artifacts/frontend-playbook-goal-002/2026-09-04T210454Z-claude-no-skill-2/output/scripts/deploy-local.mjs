#!/usr/bin/env node
// Deploys the tip jar to the local chain, then wires the addresses into the web app.
//
//   1. forge script script/Deploy.s.sol --broadcast   (writes contracts/deployments/<chainId>.json)
//   2. refresh web/lib/tipJarAbi.ts from the fresh build
//   3. write web/.env.local so `npm run dev:web` picks up the new addresses
import { spawnSync } from 'node:child_process'
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const rpcUrl = process.env.RPC_URL ?? 'http://127.0.0.1:8545'

// Anvil's default accounts #1-#3. Used only for the local browser-wallet-free dev connector.
const DEV_ACCOUNTS = [
  '0x70997970C51812dc3A010C7d01b50e0d17dc79C8',
  '0x3C44CdDdB6a900fa2b585dd299e03d12FA4293BC',
  '0x90F79bf6EB2c4f870365E785982E1f101E93b906',
]

function run(command, args, options = {}) {
  const result = spawnSync(command, args, { stdio: 'inherit', ...options })
  if (result.error?.code === 'ENOENT') {
    console.error(`\n\`${command}\` not found. Install Foundry: https://getfoundry.sh`)
    process.exit(1)
  }
  if (result.status !== 0) process.exit(result.status ?? 1)
}

console.log(`Deploying to ${rpcUrl} ...\n`)
run('forge', ['script', 'script/Deploy.s.sol:Deploy', '--rpc-url', rpcUrl, '--broadcast'], {
  cwd: resolve(root, 'contracts'),
})

const chainId = await fetch(rpcUrl, {
  method: 'POST',
  headers: { 'content-type': 'application/json' },
  body: JSON.stringify({ jsonrpc: '2.0', id: 1, method: 'eth_chainId', params: [] }),
})
  .then((response) => response.json())
  .then((body) => Number(body.result))

const deploymentPath = resolve(root, `contracts/deployments/${chainId}.json`)
const deployment = JSON.parse(await readFile(deploymentPath, 'utf8'))

run(process.execPath, [resolve(root, 'scripts/sync-abi.mjs')])

// The dev connector only makes sense against a local chain whose accounts anvil has unlocked.
const isLocalChain = chainId === 31337
const envLines = [
  '# Generated by `npm run deploy:local`. Edit freely — re-running overwrites it.',
  `NEXT_PUBLIC_CHAIN_ID=${chainId}`,
  `NEXT_PUBLIC_RPC_URL=${rpcUrl}`,
  `NEXT_PUBLIC_TIP_JAR_ADDRESS=${deployment.tipJar}`,
  `NEXT_PUBLIC_USDC_ADDRESS=${deployment.token}`,
  '',
  '# The local deploy put a MockUSDC here, so the page can offer a faucet button.',
  `NEXT_PUBLIC_MOCK_TOKEN=${deployment.mockToken ? 'true' : 'false'}`,
  '',
  '# Lets you connect without a browser wallet by using anvil\'s unlocked accounts.',
  '# Leave this empty on any public network.',
  `NEXT_PUBLIC_DEV_ACCOUNTS=${isLocalChain ? DEV_ACCOUNTS.join(',') : ''}`,
  '',
]
await writeFile(resolve(root, 'web/.env.local'), envLines.join('\n'))

console.log(`
Tip jar   ${deployment.tipJar}
Token     ${deployment.token}${deployment.mockToken ? '  (MockUSDC, mint from the page)' : ''}
Owner     ${deployment.owner}
Chain     ${chainId}

Wrote web/.env.local. Next: npm run dev:web`)
