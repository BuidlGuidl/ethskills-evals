#!/usr/bin/env bash
# Copies the compiled TipJar/ERC-20 ABIs out of contracts/out into the front end
# as typed TypeScript consts, so the UI can never drift from the contract.
#
# Usage: ./scripts/sync-abi.sh
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$ROOT/web/src/abi"
mkdir -p "$OUT"

forge build --root "$ROOT/contracts" > /dev/null

write_abi() {
  local artifact="$1" name="$2" file="$3"
  {
    echo "// Generated by scripts/sync-abi.sh - do not edit by hand."
    echo "export const $name = $(jq -c '.abi' "$artifact") as const;"
  } > "$OUT/$file"
  echo "wrote web/src/abi/$file"
}

write_abi "$ROOT/contracts/out/TipJar.sol/TipJar.json" "tipJarAbi" "tipJar.ts"
write_abi "$ROOT/contracts/out/MockUSDC.sol/MockUSDC.json" "erc20Abi" "erc20.ts"
