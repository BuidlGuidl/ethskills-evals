#!/usr/bin/env bash
# Regenerates the frontend ABI from the compiled artifact, so the app can never
# drift from the contract. Run after any change to src/TipJar.sol.

source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

require_cmd forge "Install Foundry: curl -L https://foundry.paradigm.xyz | bash && foundryup"
require_cmd jq "Install jq (e.g. apt install jq / brew install jq)"

ARTIFACT="$ROOT_DIR/contracts/out/TipJar.sol/TipJar.json"
OUT="$ROOT_DIR/web/src/abi/tipJar.ts"

log "Compiling contracts"
(cd "$ROOT_DIR/contracts" && forge build --silent)
[ -f "$ARTIFACT" ] || die "Artifact not found at $ARTIFACT"

mkdir -p "$(dirname "$OUT")"
{
  echo "// Generated by scripts/sync-abi.sh from contracts/out/TipJar.sol/TipJar.json."
  echo "// Do not edit by hand -- run \`npm run sync-abi\` after changing the contract."
  echo "export const tipJarAbi = $(jq -c '.abi' "$ARTIFACT") as const;"
} > "$OUT"

log "Wrote $OUT"
