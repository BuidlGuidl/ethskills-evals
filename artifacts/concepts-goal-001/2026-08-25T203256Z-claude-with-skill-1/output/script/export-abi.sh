#!/usr/bin/env bash
# Regenerates backend/src/abi.ts from the compiled artifact, so the backend can never drift
# from the deployed contract. Run after any change to src/.
set -euo pipefail
cd "$(dirname "$0")/.."
forge build >/dev/null
ABI=$(jq -c '.abi' out/SubscriptionBilling.sol/SubscriptionBilling.json)
{
  echo "// Generated by script/export-abi.sh — do not edit by hand."
  echo "// Regenerate with: ./script/export-abi.sh"
  echo "export const subscriptionBillingAbi = $ABI as const;"
} > backend/src/abi.ts
npx --yes prettier --write backend/src/abi.ts 2>/dev/null || true
echo "wrote backend/src/abi.ts"
