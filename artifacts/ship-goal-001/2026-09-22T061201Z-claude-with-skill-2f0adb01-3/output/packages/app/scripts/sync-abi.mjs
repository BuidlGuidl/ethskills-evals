#!/usr/bin/env node
/**
 * Copies the compiled Toolshed ABI into src/lib/abi.ts so the app builds without Foundry.
 * Run `npm run sync-abi` after changing the contract (needs `forge build` first).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const artifact = join(here, "../../contracts/out/Toolshed.sol/Toolshed.json");
const target = join(here, "../src/lib/abi.ts");

const { abi } = JSON.parse(readFileSync(artifact, "utf8"));

writeFileSync(
  target,
  `// Generated by \`npm run sync-abi\` from packages/contracts/out/Toolshed.sol/Toolshed.json.
// Do not edit by hand. USDC is read through viem's built-in \`erc20Abi\`.
export const toolshedAbi = ${JSON.stringify(abi, null, 2)} as const;
`,
);
console.log(`wrote ${target} (${abi.length} ABI entries)`);
