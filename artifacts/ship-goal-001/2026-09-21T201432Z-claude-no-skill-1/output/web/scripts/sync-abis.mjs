// Copies the ABIs out of the Foundry build into src/abis so the frontend is typed against the real
// contracts. Run `npm run sync-abis` after changing anything in ../contracts/src.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const out = resolve(here, '../../contracts/out')
const dest = resolve(here, '../src/abis')
mkdirSync(dest, { recursive: true })

const artifacts = [
  ['Toolshed.sol/Toolshed.json', 'toolshed', 'toolshedAbi'],
  ['MemberRegistry.sol/MemberRegistry.json', 'memberRegistry', 'memberRegistryAbi'],
  ['MockUSDC.sol/MockUSDC.json', 'erc20', 'erc20Abi'],
]

for (const [artifact, file, name] of artifacts) {
  const { abi } = JSON.parse(readFileSync(resolve(out, artifact), 'utf8'))
  const body = `// Generated by scripts/sync-abis.mjs from contracts/out/${artifact}. Do not edit by hand.\nexport const ${name} = ${JSON.stringify(
    abi,
    null,
    2,
  )} as const\n`
  writeFileSync(resolve(dest, `${file}.ts`), body)
  console.log(`wrote src/abis/${file}.ts`)
}
