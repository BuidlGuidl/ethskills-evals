// Generate a real proof, offline, and freeze it into test/fixtures/vote-proof.json so
// `forge test` can exercise the actual verifier without needing the JS/Noir toolchain.
//
// This is the regression net for the seam that breaks silently: public-input order between
// main.nr, AnonVoting.sol and js/lib/prove.mjs. Reorder any of them and this fixture fails.
//
// Usage: node js/fixture.mjs
import { mkdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { IMT } from "@zk-kit/imt";
import { poseidonHash2, commitmentOf, nullifierHashOf, ZERO_VALUE, TREE_DEPTH } from "./lib/poseidon.mjs";
import { VoteProver, toHexProof } from "./lib/prove.mjs";

const OUT = fileURLToPath(new URL("../test/fixtures", import.meta.url));

const ELECTORATE = 8;
const VOTER_INDEX = 3;
const PROPOSAL_ID = 1n;
const SUPPORT = true;

// Fixed, obviously-fake secrets. A real member's come from deriveNote(); these only need to
// be deterministic so the fixture is reproducible.
const secretOf = (i) => 1000n + BigInt(i);
const nullifierOf = (i) => 2000n + BigInt(i);

const run = async () => {
  const tree = new IMT((n) => poseidonHash2(n[0], n[1]), TREE_DEPTH, ZERO_VALUE, 2, []);
  const commitments = [];
  for (let i = 0; i < ELECTORATE; i++) {
    const c = commitmentOf(secretOf(i), nullifierOf(i));
    commitments.push(c);
    tree.insert(c);
  }

  const path = tree.createProof(VOTER_INDEX);
  const nullifierHash = nullifierHashOf(nullifierOf(VOTER_INDEX), PROPOSAL_ID);

  const prover = await VoteProver.create();
  const proofData = await prover.prove({
    root: tree.root,
    proposalId: PROPOSAL_ID,
    nullifierHash,
    vote: SUPPORT ? 1n : 0n,
    secret: secretOf(VOTER_INDEX),
    nullifier: nullifierOf(VOTER_INDEX),
    pathElements: path.siblings.map((s) => BigInt(Array.isArray(s) ? s[0] : s)),
    pathIndices: path.pathIndices.map((i) => i === 1),
  });
  if (!(await prover.verifyLocally(proofData))) throw new Error("fixture proof does not verify");
  await prover.destroy();

  const hex = (v) => "0x" + BigInt(v).toString(16).padStart(64, "0");
  mkdirSync(OUT, { recursive: true });
  writeFileSync(
    `${OUT}/vote-proof.json`,
    JSON.stringify(
      {
        _comment: "Generated by js/fixture.mjs. Regenerate whenever the circuit changes.",
        commitments: commitments.map(hex), // insert in this order to reproduce the root
        root: hex(tree.root),
        proposalId: Number(PROPOSAL_ID),
        nullifierHash: hex(nullifierHash),
        support: SUPPORT,
        proof: toHexProof(proofData.proof),
      },
      null,
      2,
    ),
  );
  console.log(`wrote test/fixtures/vote-proof.json (${proofData.proof.length}-byte proof)`);
};

run().catch((e) => { console.error(e); process.exit(1); });
