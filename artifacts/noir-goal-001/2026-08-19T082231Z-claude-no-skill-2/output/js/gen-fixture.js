#!/usr/bin/env node
/**
 * Generate test/fixtures/ballot.json: real proofs the Solidity tests verify onchain.
 *
 * No chain is needed - a ballot proof only depends on the member tree, the ballot
 * contract's address and the submitter's address. The tests deploy PrivateBallot at
 * the fixed address below (via getCode + etch) so `voteScope` comes out the same.
 *
 * Re-run this whenever circuits/vote/src changes, otherwise the fixture proofs no
 * longer match the regenerated verification key:
 *
 *   bash scripts/build-circuit.sh && node js/gen-fixture.js
 */
import { writeFile, mkdir } from "node:fs/promises";
import { join } from "node:path";
import { Identity, voteScope } from "./core/identity.js";
import { buildTree, merkleProof } from "./core/tree.js";
import { toHex32 } from "./core/hash.js";
import { ROOT } from "./core/chain.js";
import { proveBallot, shutdownProver } from "./core/prover.js";
import { step, info, fail } from "./core/cli.js";

/** Where test/PrivateBallot.t.sol pins the ballot contract. */
const BALLOT_ADDRESS = "0x00000000000000000000000000000000000BA110";
/** anvil account 9 - a non-member relayer. */
const RELAYER = "0xa0Ee7A142d267C1f36714E4a8F75612F20a79720";
const PROPOSAL_ID = 0n;
const MEMBER_COUNT = 8;

async function main() {
  step(1, "Build a member set");
  const identities = Array.from({ length: MEMBER_COUNT }, (_, i) =>
    Identity.fromPassphrase(`fixture member ${i}`),
  );
  const commitments = identities.map((id) => id.commitment);
  const tree = buildTree(commitments);
  info("members", MEMBER_COUNT);
  info("root", toHex32(tree.root));

  const scope = voteScope(BALLOT_ADDRESS, PROPOSAL_ID);
  info("vote scope", toHex32(scope));

  step(2, "Prove two ballots");
  const plan = [
    { label: "A", voter: 2, support: true },
    { label: "B", voter: 5, support: false },
  ];

  const fixture = {
    _comment: "Generated by js/gen-fixture.js - regenerate after any circuit change.",
    ballot: BALLOT_ADDRESS,
    relayer: RELAYER,
    proposalId: Number(PROPOSAL_ID),
    root: toHex32(tree.root),
    voteScope: toHex32(scope),
    commitments: commitments.map(toHex32),
  };

  for (const { label, voter, support } of plan) {
    const { siblings, pathBits } = merkleProof(tree, voter);
    const nullifier = identities[voter].nullifier(scope);
    const { proof } = await proveBallot({
      root: tree.root,
      scope,
      nullifier,
      support,
      relayer: RELAYER,
      secret: identities[voter].secret,
      pathBits,
      siblings,
    });
    fixture[`ballot${label}Support`] = support;
    fixture[`ballot${label}Nullifier`] = toHex32(nullifier);
    fixture[`ballot${label}Proof`] = proof;
    info(`ballot ${label}`, `leaf ${voter}, ${support ? "yes" : "no"}, ${(proof.length - 2) / 2} bytes`);
  }

  const dir = join(ROOT, "test", "fixtures");
  await mkdir(dir, { recursive: true });
  const path = join(dir, "ballot.json");
  await writeFile(path, JSON.stringify(fixture, null, 2) + "\n");

  step(3, "Done");
  info("written", path);
}

try {
  await main();
} catch (err) {
  await shutdownProver();
  fail(err.stack ?? err.message);
}
await shutdownProver();
process.exit(0);
