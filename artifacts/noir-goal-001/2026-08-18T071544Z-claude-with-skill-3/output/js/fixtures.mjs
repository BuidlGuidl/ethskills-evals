#!/usr/bin/env node
// Regenerates contracts/test/fixtures/ballots.json — real proofs for the Solidity
// tests, so `forge test` exercises the actual HonkVerifier rather than a mock.
//
//   node js/fixtures.mjs
//
// Re-run this whenever circuits/ballot changes (the verifier and the proof
// serialisation both change with it).

import { writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { keccak256, toUtf8Bytes } from "ethers";
import { LeanIMT } from "@zk-kit/lean-imt";
import { deriveIdentity, hash2, nullifierHashFor } from "./lib/identity.mjs";
import { Prover } from "./lib/prove.mjs";

const OUT = fileURLToPath(new URL("../contracts/test/fixtures/ballots.json", import.meta.url));
const MEMBERS = 8;
const PROPOSAL_ID = 0;

// Deterministic test secrets — test vectors only, never use these for real.
const identities = Array.from({ length: MEMBERS }, (_, i) =>
  deriveIdentity(keccak256(toUtf8Bytes(`anon-voting-test-member-${i}`)))
);

const tree = new LeanIMT(hash2);
for (const identity of identities) tree.insert(identity.commitment);

console.log(`built a ${MEMBERS}-leaf member tree, root ${tree.root}`);

// Two ballots by two different members: one yes, one no.
const plan = [
  { member: 2, vote: 1 },
  { member: 5, vote: 0 },
];

const prover = await Prover.create();
const ballots = [];
for (const { member, vote } of plan) {
  console.log(`proving ballot: member ${member}, vote ${vote}…`);
  const ballot = await prover.ballot({
    identity: identities[member],
    tree,
    proposalId: PROPOSAL_ID,
    vote,
    expectedRoot: tree.root,
  });
  ballots.push({
    memberIndex: member,
    vote,
    nullifierHash: ballot.nullifierHash.toString(),
    proof: ballot.proof,
    publicInputs: ballot.publicInputs,
  });
}

await prover.close();

const fixture = {
  note: "generated by js/fixtures.mjs — regenerate after any change to circuits/ballot",
  proposalId: PROPOSAL_ID,
  root: tree.root.toString(),
  commitments: identities.map((i) => i.commitment.toString()),
  // Poseidon vectors cross-checked against the Noir circuit (see
  // `nargo test --show-output print_parity_vectors`) and asserted in AnonVoting.t.sol.
  poseidonVectors: {
    a: ["1", "111", "7"],
    b: ["2", "222", "13"],
    expected: [hash2(1n, 2n), hash2(111n, 222n), hash2(7n, 13n)].map(String),
  },
  unusedNullifier: nullifierHashFor(identities[7].identityNullifier, PROPOSAL_ID).toString(),
  ballots,
};

await mkdir(new URL("../contracts/test/fixtures/", import.meta.url), { recursive: true });
await writeFile(OUT, JSON.stringify(fixture, null, 2) + "\n");
console.log(`wrote ${OUT}`);
