#!/usr/bin/env node
/**
 * Bakes one real proof into contracts/test/fixtures/ballot.json so
 * contracts/test/AnonymousBallot.t.sol can exercise the actual HonkVerifier
 * without a chain, a prover or a network.
 *
 *   node scripts/gen-fixture.mjs
 *
 * Re-run whenever the circuit changes — a stale fixture will fail the Solidity
 * test, which is exactly the alarm you want.
 *
 * The identities below are derived from fixed constants so the fixture is
 * reproducible. NEVER do this for a real member: a deterministic secret is not
 * a secret, and anyone could recompute their nullifier and vote for them.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { ROOT } from "./client/env.mjs";
import { hash2, toHex32 } from "./client/poseidon.mjs";
import { MerkleTree } from "./client/tree.mjs";
import { nullifierHashFor } from "./client/identity.mjs";
import { proveVote, voteWitnessInputs } from "./client/prover.mjs";

const MEMBERS = 12;
const VOTER = 5; // leaf index of the member casting the fixtured ballot
const PROPOSAL_ID = 1n;
const VOTE = 1n; // yes

const identities = [];
for (let i = 0; i < MEMBERS; i++) {
  const secret = hash2(1000n, BigInt(i));
  const nullifierSecret = hash2(2000n, BigInt(i));
  identities.push({ secret, nullifierSecret, commitment: hash2(secret, nullifierSecret) });
}

const tree = new MerkleTree();
identities.forEach((id) => tree.insert(id.commitment));

const note = identities[VOTER];
const nullifierHash = nullifierHashFor(note.nullifierSecret, PROPOSAL_ID);

console.log(`root       ${toHex32(tree.root)}`);
console.log(`voter leaf ${VOTER}`);
console.log(`nullifier  ${toHex32(nullifierHash)}`);
console.log("proving...");

const { proofHex } = await proveVote(
  voteWitnessInputs({
    root: tree.root,
    proposalId: PROPOSAL_ID,
    nullifierHash,
    vote: VOTE,
    note,
    merkleProof: tree.proof(VOTER),
  }),
);

const out = {
  _comment: "generated by scripts/gen-fixture.mjs — do not edit by hand",
  commitments: identities.map((id) => toHex32(id.commitment)),
  root: toHex32(tree.root),
  proposalId: Number(PROPOSAL_ID),
  voterLeafIndex: VOTER,
  vote: Number(VOTE),
  nullifierHash: toHex32(nullifierHash),
  proof: proofHex,
};

const path = join(ROOT, "contracts", "test", "fixtures", "ballot.json");
writeFileSync(path, JSON.stringify(out, null, 2) + "\n");
console.log(`wrote ${path} (${(proofHex.length - 2) / 2} byte proof)`);
