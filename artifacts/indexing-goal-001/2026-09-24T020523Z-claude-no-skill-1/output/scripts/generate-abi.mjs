// Copies the compiled Streak ABI out of contracts/out into indexer/abis so the
// indexer can never drift from the deployed contract. Run after `forge build`.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const artifact = join(root, "contracts/out/Streak.sol/Streak.json");
const target = join(root, "indexer/abis/StreakAbi.ts");

let json;
try {
  json = JSON.parse(readFileSync(artifact, "utf8"));
} catch {
  console.error(`Missing ${artifact}. Run \`forge build\` in contracts/ first.`);
  process.exit(1);
}

mkdirSync(dirname(target), { recursive: true });
writeFileSync(
  target,
  `// Generated by scripts/generate-abi.mjs from contracts/out/Streak.sol/Streak.json.\n` +
    `// Do not edit by hand; run \`npm run abi\` after changing the contract.\n` +
    `export const StreakAbi = ${JSON.stringify(json.abi, null, 2)} as const;\n`,
);
console.log(`Wrote ${target}`);
