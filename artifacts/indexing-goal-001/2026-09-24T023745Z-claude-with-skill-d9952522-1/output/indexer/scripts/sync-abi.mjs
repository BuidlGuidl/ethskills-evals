// Regenerates abis/StreakAbi.ts from the Foundry build output.
// Run after changing contracts/src/Streak.sol:
//   (cd ../contracts && forge build) && npm run abi
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const artifact = resolve(here, "../../contracts/out/Streak.sol/Streak.json");
const out = resolve(here, "../abis/StreakAbi.ts");

let json;
try {
  json = JSON.parse(readFileSync(artifact, "utf8"));
} catch {
  console.error(`No artifact at ${artifact}. Run \`forge build\` in ../contracts first.`);
  process.exit(1);
}

writeFileSync(
  out,
  "// Generated by scripts/sync-abi.mjs from contracts/out/Streak.sol/Streak.json.\n" +
    "// Do not edit by hand; edit the contract and re-run `npm run abi`.\n" +
    `export const StreakAbi = ${JSON.stringify(json.abi, null, 2)} as const;\n`,
);
console.log(`wrote ${out} (${json.abi.length} entries)`);
