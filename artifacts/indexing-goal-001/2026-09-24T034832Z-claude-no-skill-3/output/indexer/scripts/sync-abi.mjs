// Regenerates abis/StreakAbi.ts from the Foundry build artifact.
// Usage: (cd ../contracts && forge build) && node scripts/sync-abi.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const artifactPath = join(here, "..", "..", "contracts", "out", "Streak.sol", "Streak.json");
const outPath = join(here, "..", "abis", "StreakAbi.ts");

const { abi } = JSON.parse(readFileSync(artifactPath, "utf8"));

writeFileSync(
  outPath,
  `// Generated by scripts/sync-abi.mjs from contracts/out/Streak.sol/Streak.json.\n` +
    `// Do not edit by hand.\n` +
    `export const StreakAbi = ${JSON.stringify(abi, null, 2)} as const;\n`,
);

console.log(`wrote ${outPath} (${abi.length} entries)`);
