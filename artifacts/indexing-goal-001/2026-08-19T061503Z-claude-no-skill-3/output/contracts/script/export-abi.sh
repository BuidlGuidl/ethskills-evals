#!/usr/bin/env bash
# Regenerates indexer/abis/StreakAbi.ts from the compiled Streak artifact.
# Run after changing src/Streak.sol.
set -euo pipefail
cd "$(dirname "$0")/.."
forge build >/dev/null
abi=$(jq '.abi' out/Streak.sol/Streak.json)
{
  echo "// Generated by contracts/script/export-abi.sh — do not edit by hand."
  echo "export const StreakAbi = $abi as const;"
} > ../indexer/abis/StreakAbi.ts
echo "wrote indexer/abis/StreakAbi.ts"
